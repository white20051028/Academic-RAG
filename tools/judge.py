# ---------------- 一、闲聊识别（不检索，不调模型） ----------------

# 只放"整句就是打招呼"的表达。判断方式是：把这些词剥掉后还剩不剩实质内容。
# 所以「你好，转专业要什么条件」不会被误判——剥掉"你好"还剩正文。
SMALLTALK_WORDS = (
    "你好", "您好", "在吗", "在不在", "早上好", "中午好", "下午好", "晚上好",
    "hi", "hello", "hey",
    "谢谢", "感谢", "多谢", "辛苦了",
    "你是谁", "你是什么", "你能做什么", "你能干什么", "你会什么", "介绍一下自己",
    "晚安", "拜拜", "再见", "好的", "ok",
)

# 剥掉问候词后，剩下这些字符不算"实质内容"
_FILLER = set(" \t\r\n，。！？、,.!?~～呀啊呢吧哦嘛哈嘿嗯")

SMALLTALK_REPLY = """你好，我是西科大教务政策问答 🙋

我能回答的是**教务处公开文件里写着的东西**：
学籍 · 学位 · 学分认定 · 辅修 / 微专业 · 转专业 · 重修 · 本硕连读 · 课程设置

不知道从哪问起的话，可以试试：

- 「转专业需要什么条件」
- 「绩点 2.1 能拿到学位证吗」
- 「挂科了要重修吗」

你直接问就行。"""


def is_smalltalk(question: str) -> bool:
    """整句只是打招呼/致谢 → True。规则判断，不调模型。

    为什么用规则不用模型：
    1. 这类问题不需要理解，关键词足够；
    2. 要在检索之前拦住，多一次调用就是多 2 秒白等；
    3. 判错了代价低（最多是把"你好"当成了教务问题，走老流程）。

    宁可漏判，不可误判：漏判的后果是回到原来的拒答流程，
    误判的后果是把真问题当成闲聊答非所问——后者严重得多。
    """
    text = question.strip().lower()
    if not text:
        return True

    rest = text
    for word in sorted(SMALLTALK_WORDS, key=len, reverse=True):
        rest = rest.replace(word, "")

    # 剥完只剩标点/语气词，才算闲聊
    return all(ch in _FILLER for ch in rest)


# ---------------- 二、资料够不够（调模型） ----------------

def build_probe(question: str, context: str) -> str:
    """把「问题 + 前 5 条资料」拼成三分类判断的 prompt。

    设计要点（每条都是踩出来的）：

    1. **用 A/B/C 单字母，不用「够/不够」**
       v14 踩过：「能不能」有两个意思（用户能不能办成 / 资料能不能答），
       模型答「不能 | 资料中大三学生不符合」——它答对了，我们解析错了。
       单字母没有歧义。

    2. **「检索永远返回 5 条」必须写进 prompt**
       实测：「食堂有哪些」返回 5 条全不相关的（sim 0.522），
       「图书馆开放时间」返回 5 条全不相关（sim 0.540）。
       所以判据不能是「有没有结果」，必须是「这 5 条能不能用」。

    3. **A 类门槛卡严**
       「食堂」一度想归成无关，用户指出：每个大学都有食堂，
       学生问「食堂」本意就是「你们学校食堂有哪些」，
       回「我只懂教务」等于答非所问。正确做法是「资料里没有 + 指路」。
    """
    return (
        "你是西安科技大学教务问答系统的分诊员。判断下面这次检索到的资料属于哪一类。\n\n"

        "【提问者的身份】\n"
        "来问的都是西安科技大学的在校学生（除非他明确说自己是老师）。\n"
        "所以即使问题很短很口语，也要按「校内事务」理解：\n"
        "  「服兵役」→ 西科大学生服兵役有什么政策、要求、影响\n"
        "  「上课」  → 我的课表/上课时间在哪查\n"
        "  「退学」  → 退学的条件和流程\n"
        "  「评教」「成绩」→ 默认学生视角\n\n"

        "【三个类别】\n"
        "A = 和这所学校**完全没关系**（吃什么、今天天气、动漫角色谁强）\n"
        "    注意：**食堂、宿舍、校车、图书馆、课表、操场都不算 A**——\n"
        "    学校里有这些东西，它们是校内事务，只是可能不归教务处管。\n"
        "B = 校内事务，资料里有能直接回答的内容\n"
        "C1 = 校内事务，但**资料里根本没有这个话题**\n"
        "     特征：返回的 5 条资料跟问题八竿子打不着（问食堂，返回的是公选课通知）\n"
        "     回答这一类的正确方式是「教务处资料里没有，要去 XX 部门查」\n"
        "C2 = 校内事务，**资料有相关内容，但缺关键一块**\n"
        "     特征：资料确实在讲这件事，但缺你要的那一层\n"
        "     例：问「通识教育一共多少学分」，资料只列了各类小项，没给总数\n"
        "     例：问「本硕连读学制几年」，资料讲了选拔和管理，没讲学制\n"
        "     这一类值得再查一次（读完整文件、或换份文件）\n\n"
        "**C1 和 C2 的区别很重要**：C1 再查也是白查（资料里根本没有），\n"
        "C2 再查有机会查到。判错方向：C2 判成 C1 → 该救的没救；\n"
        "C1 判成 C2 → 白跑一趟，用户多等十几秒。\n\n"

        "【B 和 C 怎么分：问自己一句】\n"
        "用户看完这些资料，还需要自己去翻文件吗？\n"
        "  需要 → C     不需要 → B\n\n"

        "【⚠️ 最容易判错的一种：资料能得出否定结论】\n"
        "如果资料写明了「限定某范围」，而用户不在这个范围内，\n"
        "那资料已经**足够**回答「你不能」，不是不够。这种情况判 B。\n"
        "  例：问「大三绩点4.0能转专业吗」，资料写「第一～二款限定本科一年级」\n"
        "      → 够了，可以答「不能，绩点那条只对大一开放」→ B\n"
        "  只有当资料连「用户这种情况归哪一条」都没写，才判 C。\n"
        "  例：资料只写「转专业有条件」但一个字都没提年级 → C\n\n"

        "【重要：检索永远返回 5 条】\n"
        "不管相不相关都会有 5 条。所以不要因为「有结果」就判 B。\n"
        "要看这 5 条到底能不能回答问题——\n"
        "  「食堂有哪些」返回 5 条，全是公选课、科技竞赛的通知 → C（资料没有）\n"
        "  「转专业要什么条件」返回的正好是转专业通知全文 → B\n\n"

        "【例子】\n"
        "  问「转专业要什么条件」 + 资料有全部条款        → B\n"
        "  问「大三绩点4.0能转专业吗」+ 资料只说限一年级   → C\n"
        "  问「图书馆开放时间」     + 返回的 5 条都不相关  → C\n"
        "  问「吃什么」                                    → A\n\n"

        f"资料：\n{context[:3000]}\n\n"
        f"用户问题：{question}\n\n"

        "只输出一行，格式严格如下（类别后面跟 | 和一句理由）：\n"
        "A  | 原因：<为什么与学校无关>\n"
        "B  | 依据：<摘出资料里能回答用户的那句话>\n"
        "C1 | 原因：<资料里根本没有哪个话题>\n"
        "C2 | 原因：<有什么内容，但缺哪一块>\n"
    )


def parse_kind(answer: str) -> tuple[str, str]:
    """解析分类结果，返回 (类别, 理由)。类别是 A / B / C1 / C2。

    解析不出来默认 B。理由：B 是「正常生成答案」，后面还有引用给用户核对。
    默认成 C1/C2 会多跑一次 Agent 或过早指路；默认成 A 会把问题当闲聊（更糟）。
    所以 B 是最安全的兜底。

    **C1/C2 必须先于 C 匹配**：字符串 "C1" 也满足 startswith("C")，
    顺序反了会把 C1 解析成 C，Agent 的触发器就失效了。
    """
    text = (answer or "").strip()
    first = text.split("\n", 1)[0].strip()

    for kind in ("C1", "C2", "A", "B", "C"):
        # 容忍 "A |"、"A｜"、"A类"、"【A】" 这几种写法
        if first.startswith(kind) or first.startswith(f"{kind}类") or first.startswith(f"【{kind}】"):
            reason = ""
            for sep in ("|", "｜", "："):
                if sep in first:
                    reason = first.split(sep, 1)[1].strip()
                    break
            for prefix in ("原因：", "依据：", "原因:", "依据:"):
                if reason.startswith(prefix):
                    reason = reason[len(prefix):].strip()
            # 只写 "C" 没写子类的，归到 C1（更保守：直接指路，不白跑 Agent）
            if kind == "C":
                kind = "C1"
            return kind, reason

    return "B", text[:120]


def build_probe_legacy(question: str, context: str) -> str:
    """旧版的「够/不够」probe。留作对照和回退用，线上不再调用。"""
    return (
        "任务：判断下面这些资料**够不够**支撑一个答案。\n\n"
        f"资料：\n{context[:3000]}\n\n"
        f"用户问题：{question}\n\n"
        "请按下面格式回答：\n"
        "够 | 依据：<摘出资料里能帮到用户的那句话>\n"
        "或\n"
        "不够 | 原因：<为什么资料帮不上>\n"
    )


def parse_verdict(answer: str) -> bool:
    """旧接口：解析「够/不够」。新代码请用 parse_kind。

    「够」而不是「能」：2026-11-10 踩过——判断层问的是「资料够不够」，
    但它理解成「用户能不能办成」。用户问「大三绩点2.8能转专业吗」，
    资料写「限定本科一年级」，模型答「不能 | 原因：资料中提到大三不符合」——
    它答对了，但那个「不能」是「用户不能」，被解析成「资料不够」。

    「能不能」有两个意思，「够不够」只有一个。v15 干脆换成 A/B/C。
    """
    first = (answer or "").strip().split("\n", 1)[0]
    return first.startswith("够") and "依据" in first


def classify(question: str, context: str, client, model: str) -> tuple[str, str]:
    """三分类。异常时返回 ("B", "")——宁可直接答（带引用），不要误拒或误进 Agent。"""
    try:
        r = client.chat.completions.create(
            model=model,
            messages=[{"role": "user", "content": build_probe(question, context)}],
            max_tokens=150,
            temperature=0,
        )
        return parse_kind(r.choices[0].message.content or "")
    except Exception:  # noqa: BLE001
        return "B", ""


def check_answerable(question: str, context: str, client, model: str) -> bool:
    """旧接口，返回「资料够不够」。内部走三分类，B 才算够。

    留着是为了不动现有调用点（app.py / eval_judge.py）。
    接 Agent 时改调 classify()，拿完整的 A/B/C。
    """
    kind, _ = classify(question, context, client, model)
    return kind == "B"
