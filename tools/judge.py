"""判断层：资料够不够、要不要拒、还是纯粹闲聊。

**为什么单独一个模块，而不是留在 app.py 里**

2026-11-06 踩过一个坑：`tools/eval.py` 里写死了 `vec_mode` 默认值，
和 `app.py` 的实际行为分叉了半个月没人发现——「测的」和「跑的」不是一回事。

判据层的逻辑（prompt、判定规则、三分类）比 vec_mode 更容易分叉，
所以必须只有一份：线上（app.py）和评测（tools/eval_judge.py）都 import 这里。

这个模块不读环境变量、不建 client——client 由调用方传进来。
这样它可以在 Streamlit 里跑，也可以在命令行脚本里跑。
"""

import re

# 两个决策阈值。**必须只有一份**：app.py 和 eval_judge.py 都从这里 import，
# 否则改了一边忘了另一边，"测的"和"跑的"立刻分叉。
DEFAULT_MIN_SCORE = 0.60    # 已不再用于判定，只用于界面提示「这条分数偏低但救了回来」
GRAY_HIGH = 0.70            # 同上，保留给历史评测脚本对比用
FAST_PATH = 0.78            # 高于它直接答，不进判断层（实测口语集最高 0.743，基本不触发）

# ---------------- 一、闲聊识别（不检索，不调模型） ----------------

# 只放"整句就是打招呼"的表达。判断方式是：把这些词剥掉后还剩不剩实质内容。
# 所以「你好，转专业要什么条件」不会被误判——剥掉"你好"还剩正文。
SMALLTALK_WORDS = (
    "你好", "您好", "在吗", "在不在", "早上好", "中午好", "下午好", "晚上好",
    "hi", "hello", "hey",
    "谢谢", "感谢", "多谢", "辛苦了",
    "你是谁", "你是什么", "你能做什么", "你能干什么", "你会什么", "介绍一下自己",
    "晚安", "拜拜", "再见", "好的", "ok",
)

# 剥掉问候词后，剩下这些字符不算"实质内容"
_FILLER = set(" \t\r\n，。！？、,.!?~～呀啊呢吧哦嘛哈嘿嗯")

SMALLTALK_REPLY = """你好，我是西科大教务政策问答 🙋

我能回答的是**教务处公开文件里写着的东西**：
学籍 · 学位 · 学分认定 · 辅修 / 微专业 · 转专业 · 重修 · 本硕连读 · 课程设置

不知道从哪问起的话，可以试试：

- 「转专业需要什么条件」
- 「绩点 2.1 能拿到学位证吗」
- 「挂科了要重修吗」

你直接问就行。"""


def is_smalltalk(question: str) -> bool:
    """整句只是打招呼/致谢 → True。规则判断，不调模型。

    为什么用规则不用模型：
    1. 这类问题不需要理解，关键词足够；
    2. 要在检索之前拦住，多一次调用就是多 2 秒白等；
    3. 判错了代价低（最多是把"你好"当成了教务问题，走老流程）。

    宁可漏判，不可误判：漏判的后果是回到原来的拒答流程，
    误判的后果是把真问题当成闲聊答非所问——后者严重得多。
    """
    text = question.strip().lower()
    if not text:
        return True

    rest = text
    for word in sorted(SMALLTALK_WORDS, key=len, reverse=True):
        rest = rest.replace(word, "")

    # 剥完只剩标点/语气词，才算闲聊
    return all(ch in _FILLER for ch in rest)


# ---------------- 二、资料够不够（调模型） ----------------

def build_probe(question: str, context: str) -> str:
    """把「问题 + 前 5 条资料」拼成判断用的 prompt。

    判据改过两次，每次都量过（见 docs/v7-判断层评测.md）：

      第一版「资料能不能回答这个问题」
        → 太松：看到体育课安排里有老师名字就说能。问数学老师，答体育老师。

      第二版「必须有直接回答的内容，而且摘出依据」
        → 太严：问「学生证丢了急用怎么办」，资料有补办流程但没提"加急" → 判不能。
          该答的 29 条里误杀 10 条，总分从 87.2% 掉到 69.2%。

      现在「能不能实质帮到用户」
        → 不要求覆盖每个限定词；拿不准倾向「能」，因为答案带引用，用户能自己核。
    """
    return (
        "任务：判断下面这些资料能不能帮用户解决他的问题。\n\n"
        "判断标准：\n"
        "- 资料里有能**实质帮助**用户的内容 → 答「能」。不要求覆盖问题的每个限定词。\n"
        "  例：问「学生证丢了急用怎么办」，资料写了补办流程但没写加急 → 能，补办流程就是答案。\n"
        "- 只有「字面相关」但领域完全不同 → 答「不能」。\n"
        "  例：问「数学老师是谁」，资料里全是体育老师名单 → 不能。\n"
        "- 只出现了问题里的词，但没给出任何可执行的信息（条件/数字/流程）→ 答「不能」。\n"
        "  例：问「实习怎么请假」，资料只写「新生入学请假不超过2周」→ 不能。\n"
        "- 拿不准的时候答「能」：回答会带资料引用，用户能自己核对。\n\n"
        f"资料：\n{context[:3000]}\n\n"
        f"用户问题：{question}\n\n"
        "请按下面格式回答：\n"
        "能 | 依据：<摘出资料里能帮到用户的那句话>\n"
        "或\n"
        "不能 | 原因：<为什么资料帮不上>\n"
    )


def parse_verdict(answer: str) -> bool:
    """解析模型回答。必须同时满足「开头说能」和「给了依据」才算能答。

    只看开头一个"能"字不够——模型经常写「能，但是……」再来一句没依据的，
    或者直接复述问题。要求它摘依据，是让它真的在资料里找过。
    """
    first = (answer or "").strip().split("\n", 1)[0]
    return first.startswith("能") and "依据" in first


def check_answerable(question: str, context: str, client, model: str) -> bool:
    """资料够不够回答这个问题。异常时返回 True（宁可多答，不可误拒）。"""
    try:
        r = client.chat.completions.create(
            model=model,
            messages=[{"role": "user", "content": build_probe(question, context)}],
            max_tokens=120,
            temperature=0,
        )
        return parse_verdict(r.choices[0].message.content or "")
    except Exception:  # noqa: BLE001
        # 判断层挂了不能把整个问答也挂掉：退回"能答"，让用户至少看到答案和引用
        return True
